// Writes the bank_items seed migration from supabase/functions/_shared/domain/questions.json
// (English translation of pit-study's bank, freeze-v1; the original is questions.ro.json). Run: node scripts/gen-bank-seed.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { levelOf } from '../supabase/functions/_shared/domain/levels.ts';

type Q = {
  id: string;
  domain: string;
  tier: 'warmup' | 'easy' | 'hard';
  bands: string[];
  prompt_ro: string;
  reference_answer_ro: string;
  rubric: unknown;
  misconceptions: unknown;
  explanation_ro: string;
};

const OUT = 'supabase/migrations/20261023120100_bank_items_seed.sql';
const bank = JSON.parse(readFileSync('supabase/functions/_shared/domain/questions.json', 'utf8')) as Q[];
const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;

const rows = bank.map(
  (q) =>
    `  (${[
      lit(q.id),
      lit(q.domain),
      lit(q.tier),
      String(levelOf(q.tier)),
      `array[${q.bands.map(lit).join(', ')}]`,
      lit(q.prompt_ro),
      lit(q.reference_answer_ro),
      `${lit(JSON.stringify(q.rubric))}::jsonb`,
      `${lit(JSON.stringify(q.misconceptions))}::jsonb`,
      lit(q.explanation_ro),
    ].join(', ')})`,
);

writeFileSync(
  OUT,
  `-- Generated by scripts/gen-bank-seed.ts from questions.json: the English translation of pit-study's bank (freeze-v1).
-- The _ro column names are kept from pit-study's schema; the content is English. Do not edit by hand.
-- Levels: warmup 1, easy 3, hard 5.
insert into public.bank_items
  (id, domain, tier, level, bands, prompt_ro, reference_answer_ro, rubric, misconceptions, explanation_ro)
values
${rows.join(',\n')}
on conflict (id) do nothing;
`,
);
console.log(`wrote ${bank.length} questions to ${OUT}`);
